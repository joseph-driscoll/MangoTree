"use client"

import type React from "react"

interface ContentBlockProps {
  id: string
  label: string
  content: string
  type: string
  pieceIndex: number
  originalPrompt: string
  tone: string
  audience: string
  voice: string
  generatedBy: string
  onContentUpdate: (newContent: string) => void
}

const ContentBlock: React.FC<ContentBlockProps> = ({
  id,
  label,
  content,
  type,
  pieceIndex,
  originalPrompt,
  tone,
  audience,
  voice,
  generatedBy,
  onContentUpdate,
}) => {
  return (
    <div>
      <h3>{label}</h3>
      <p>{content}</p>
      <p>Type: {type}</p>
      <p>Piece Index: {pieceIndex}</p>
      <p>Original Prompt: {originalPrompt}</p>
      <p>Tone: {tone}</p>
      <p>Audience: {audience}</p>
      <p>Voice: {voice}</p>
      <p>Generated By: {generatedBy}</p>
      <button onClick={() => onContentUpdate("Updated Content")}>Update Content</button>
    </div>
  )
}

interface DynamicResultsPageProps {
  content: any // Replace 'any' with a more specific type if possible
}

const DynamicResultsPage: React.FC<DynamicResultsPageProps> = ({ content }) => {
  if (!content || !content.content || !content.content.pieces) {
    return <div>No content available.</div>
  }

  return (
    <div>
      <h1>Results Page</h1>
      {content.content.pieces.map((piece: any, index: number) => (
        <ContentBlock
          key={index}
          id={content.id}
          label={piece.label}
          content={piece.content}
          type={piece.type}
          pieceIndex={index}
          originalPrompt={content.prompt}
          tone={content.tone}
          audience={content.audience}
          voice={content.voice}
          generatedBy={content.generated_by} // Add this line
          onContentUpdate={(newContent) => {
            // Handle content update
          }}
        />
      ))}
    </div>
  )
}

export default DynamicResultsPage
