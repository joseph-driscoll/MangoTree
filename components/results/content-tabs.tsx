import type React from "react"

interface ContentTabsProps {
  content: any
}

const ContentTabs: React.FC<ContentTabsProps> = ({ content }) => {
  if (!content || !content.pieces || content.pieces.length === 0) {
    return <div>No content available.</div>
  }

  return (
    <div>
      {content.pieces.map((piece: any, index: number) => (
        <ContentBlock
          key={index}
          content={piece.content}
          title={piece.title}
          generatedBy={piece.generated_by || content.generated_by}
        />
      ))}
    </div>
  )
}

interface ContentBlockProps {
  content: string
  title: string
  generatedBy?: string
}

const ContentBlock: React.FC<ContentBlockProps> = ({ content, title, generatedBy }) => {
  return (
    <div>
      <h3>{title}</h3>
      <p>{content}</p>
      {generatedBy && <p>Generated by: {generatedBy}</p>}
    </div>
  )
}

export default ContentTabs
export { ContentTabs }
